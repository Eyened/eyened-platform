"""composite FKs down the patient chain

Revision ID: b45090e1544e
Revises: 99724789b34d
Create Date: 2026-08-20

Makes the denormalized ProjectID copies structurally true rather than true by
convention. Each of Study, Series and ImageInstance gets a composite foreign
key carrying ProjectID alongside the key it already had, and after this the
database itself refuses to let a child's project drift from its parent's.

Each composite key REPLACES the single-column foreign key on the same column
rather than joining it. Two foreign-key paths between the same pair of tables
make SQLAlchemy refuse to configure the relationship (AmbiguousForeignKeysError)
and nothing imports; the replacement is also what makes the ORM copy ProjectID
parent-to-child during a flush.

The replacement is done ADD first, DROP second, so per table the two keys
coexist for exactly one statement. That order is the point, not an accident.
InnoDB is perfectly willing to hold two foreign keys on the same column -- the
ambiguity that forbids the end state is SQLAlchemy's mapper, which never sees
this intermediate -- and adding first is the only order in which the table is
never, at any statement boundary, without a key to its parent. Dropped first,
an interruption between the two would leave a production table with neither,
and the operator with no route back but hand-repair; and the gap between the
two is precisely where an interruption is most likely: the ADD is the slow
statement of the pair, the rebuild measured at roughly 33 s per 1.85M rows,
and so the one that times out.

Not autogenerated. This worktree has no dev/.env or dev/.env.alembic, and the
DDL grant this migration needs only works from inside the compose network --
not from the host, not via `docker exec` -- so `alembic revision
--autogenerate` could not be run here. Hand-authored to match the shape
autogenerate would produce, then parsed and executed end to end against a
throwaway MySQL 8.0.27 (upgrade, re-run, downgrade, re-run, upgrade again) on a
stub of the pre-migration schema. A human should still diff it against the live
schema before it is trusted unreviewed.

No strict-SQL-mode guard, unlike two of its predecessors. That guard protects a
`MODIFY ... NOT NULL` tightening from silently rewriting a missed row to 0.
This migration adds no column and tightens no nullability; the only thing it
needs the server to be honest about is foreign_key_checks, which is asserted
directly below.

Every index and constraint name below is copied from the model's __table_args__
verbatim. A name derived from the column instead would differ by a word
("ix_Study_PatientID_Project" vs the model's "ix_Study_Patient_Project") and the
next autogenerate would emit a spurious drop-and-add for each one.

Re-runnable, like its two predecessors and for the same reason: MySQL commits
DDL implicitly, so the ten statements below commit one at a time and an
interrupted run -- a crash, a timeout on one of the rebuilds, or an operator
recovery (`alembic stamp <down_revision>` then `alembic upgrade head`) -- can
re-enter this function with any prefix of them already applied. Each step is
guarded by the state it would produce, so a re-run picks up wherever it stopped
instead of dying on ERROR 1061 (duplicate index) and stranding the chain
half-converted. Nothing that can raise runs after the first ALTER: the one
check that could still fail on a well-formed database happens in a discovery
pass before any DDL. Verified by killing the run at each of the ten statement
boundaries and re-running from there. Downgrade is built and verified the same
way, in both respects.
"""
from typing import Sequence, Union

from alembic import op
import sqlalchemy as sa
from sqlalchemy.engine import Connection


