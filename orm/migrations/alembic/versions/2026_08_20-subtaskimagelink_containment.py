"""SubTaskImageLink containment

Revision ID: 2db0e63195db
Revises: b45090e1544e
Create Date: 2026-08-20

Gives SubTaskImageLink its own TaskID and ProjectID and points three foreign
keys at them. Two of the three replace the single-column keys the table already
had, carrying the denormalized copy alongside; the third,
`fk_SubTaskImageLink_TaskProject`, is new and is the point of the whole design:
from the moment it lands, an image from a project its task has not declared
cannot be linked by any writer -- service, script, or raw SQL -- because the
database refuses the row.

The columns and the keys ship in one migration because they have to. TaskID is
NOT NULL and no application listener can fill it for `create_from_imagesets`:
at before_flush the Task row does not exist, so the pending SubTask.TaskID is
still None. What fills it is SQLAlchemy's unit of work syncing the composite key
(SubTaskID, TaskID) -> SubTask during the flush, after the parent's INSERT.
Split the columns from the key and the script write path is broken in between.

Expect seconds. Spec 10.6 measures the three foreign keys at 1.7 s over the
87,454 rows this table holds; that figure is already the COPY-rebuild cost. A
run that takes a minute is a signal that something is wrong, not the plan being
met -- ImageInstance and Series are the tables that carry a write window, and
they were converted a migration ago.

The gate at the top of `upgrade` is the reason this file is not just DDL. This
is the one moment declared and derived coexist: once the read path switches to
the declaration there is nothing left to compare against. See `upgrade` for why
its two directions are deliberately not symmetric.

Not autogenerated. This worktree has no dev/.env or dev/.env.alembic, and the
DDL grant this migration needs only works from inside the compose network, so
`alembic revision --autogenerate` could not be run here. Hand-authored to match
the shape autogenerate would produce -- every index and constraint name is
copied from the model's __table_args__ verbatim, because a name derived from
the columns instead would differ by a word and the next autogenerate would emit
a spurious drop-and-add for it forever -- then parsed and executed end to end
against a throwaway MySQL 8.0.27 on a stub of the pre-migration schema. A human
should still diff it against the live schema before it is trusted unreviewed.

Re-runnable, like its predecessors and for the same reason: MySQL commits DDL
implicitly, so the statements below commit one at a time and an interrupted run
-- a crash, a timeout on the rebuild, or an operator recovery (`alembic stamp
<down_revision>` then `alembic upgrade head`) -- can re-enter this function with
any prefix already applied. Each step is guarded by the state it would produce.
Nothing that can raise runs after the first ALTER: the gate and the
single-column-FK discovery, the only two things here that can fail on a
well-formed database, both happen before any DDL. Verified by killing the run at
every statement boundary and re-running from each, upgrade and downgrade alike,
with a negative control on an unguarded copy.
"""
