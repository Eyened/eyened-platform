"""add TaskProject

Revision ID: 99724789b34d
Revises: 4eae42457fa2
Create Date: 2026-08-20

Creates the declaration table: the projects a task may contain, stated
directly rather than derived by walking every image up to its patient's
project. Later tasks add the foreign keys that hold data inside this
declaration; this migration only creates the table and seeds it from what
each task currently derives.

Not autogenerated. This worktree has no dev/.env or dev/.env.alembic, and the
DDL grant this migration needs only works from inside the compose network --
not from the host, not via `docker exec` -- so `alembic revision
--autogenerate` could not be run here. Hand-authored to match the shape
autogenerate would produce; a human should diff this against a live schema
before it is trusted unreviewed.

No strict-SQL-mode guard, unlike its two predecessors. That guard exists to
catch a NOT NULL conversion silently rewriting a missed row to 0 -- relevant
when a column is added nullable, backfilled by UPDATE, and only then
tightened with `MODIFY ... NOT NULL`. TaskID and ProjectID here are never
nullable: they are the table's primary key, declared NOT NULL at CREATE TABLE
time, and the backfill below is an INSERT of brand-new rows, not an UPDATE of
existing ones. There is no tightening step for the guard to protect.

No chunking, unlike its two predecessors. Those backfills rewrite 1.85M and
several hundred thousand rows respectively and are chunked specifically to
avoid holding row locks on a live, populated table for tens of seconds. This
one inserts on the order of 108 rows, computed by a single indexed join and
written to a table that has no rows and no readers yet (it does not exist
until this same migration creates it) -- chunking machinery here would be
noise with nothing to protect against.

Both DDL statements below (CREATE TABLE, CREATE INDEX) run and implicitly
commit before the INSERT is ever sent, so a re-run can reach this INSERT with
the table already created, indexed, and populated -- not only from a crash
before the INSERT's own transaction committed, but from an operator recovery
move (`alembic stamp <down_revision>` followed by `alembic upgrade head`) or
a backup restored after the DDL committed. The INSERT is written as an
anti-join against TaskProject itself (`LEFT JOIN ... WHERE tp.TaskID IS
NULL`), so a row already present is simply not selected again; re-running it
against a populated table inserts only what is still missing and is a no-op
once the declaration is complete. `INSERT IGNORE` is deliberately not used
instead: it would downgrade a foreign-key violation or truncation to a
warning, silently dropping a row instead of failing loud -- exactly the
failure a later task's equivalence gate depends on surfacing.

The INSERT reads at READ COMMITTED from inside an autocommit block. Neither
half of that pairing works without the other; the comment above the statement
says what each one is holding up and what breaks when it is dropped.
"""
