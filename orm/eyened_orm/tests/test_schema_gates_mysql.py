"""Prove, on every CI run, that the schema gates can still fail.

alembic check catches FK-action drift on all 83 foreign keys today -- but only
incidentally: it rests on the alembic==1.13.2 pin, on the MySQL dialect
reflecting FK `options`, and on env.py never gaining an include_object filter.
compare_server_default is newer still. Both are asserted here by mutating the
database and requiring the check to fail, so the day one stops working we hear
about it instead of enjoying a green check that measures nothing.

Every mutation restores in `finally`. A control that left the database altered
after a failed assertion would poison every step after it, and the failure
would be blamed on the wrong thing. That restoration is not atomic, though:
MySQL DDL auto-commits each statement, so a failure between the `DROP` and the
re-`ADD` in the FK control would leave the `finally` block's own `DROP`
erroring on a constraint that is already gone.
"""

from __future__ import annotations

import os
from datetime import date
from pathlib import Path
from uuid import uuid4

import pytest
from alembic.command import check, stamp, upgrade
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, select, text
from sqlalchemy.orm import Session

from eyened_orm import Task
from eyened_orm.config import load_database_settings
from eyened_orm.repositories.task_repository import TaskRepository
from eyened_orm.utils.env import env_flag_enabled
from eyened_orm.utils.factories import (
    admin_scope,
    make_device,
    make_image,
    make_patient,
    make_project,
    make_series,
    make_storage_backend,
    make_study,
)

pytestmark = pytest.mark.mysql

MIGRATIONS_DIR = Path(__file__).resolve().parents[2] / "migrations"


@pytest.fixture(scope="module")
def engine():
    """A live MySQL migrated to head, or a skip.

    EYENED_REQUIRE_MYSQL_TESTS turns that skip into a failure. Without it a
    misconfigured job would skip both controls and still report green, which is
    the exact failure mode they exist to rule out.
    """
    try:
        settings = load_database_settings()
        engine = create_engine(
            f"mysql+pymysql://{settings.user}:{settings.password.get_secret_value()}"
            f"@{settings.host}:{settings.port}/{settings.database}"
        )
        with engine.connect() as conn:
            conn.execute(text("SELECT 1"))
    except Exception as exc:
        if env_flag_enabled(os.environ.get("EYENED_REQUIRE_MYSQL_TESTS")):
            pytest.fail(f"EYENED_REQUIRE_MYSQL_TESTS is set but MySQL is unusable: {exc}")
        pytest.skip(f"no MySQL available: {exc}")
    return engine


@pytest.fixture(scope="module")
def alembic_config():
    """A bare ``Config``, mirroring ``alembic_utils.upgrade_to_head``.

    Passing ``alembic.ini`` here would set ``config_file_name`` and make
    env.py call ``fileConfig()`` on every ``check()`` -- six times a run,
    disabling logging via ``fileConfig``'s ``disable_existing_loggers``
    default.
    """
    config = Config()
    config.set_main_option("script_location", str(MIGRATIONS_DIR / "alembic"))
    return config


def _check_passes(engine, config) -> bool:
    """Run ``check()`` with the connection injected via ``config.attributes``.

    That is what makes env.py skip its interactive confirmation prompt: the
    guard only exempts ``check`` through ``cmd_opts.cmd``, which a
    programmatically-built ``Config`` never has, so without an injected
    connection it prompts anyway.
    """
    with engine.connect() as connection:
        config.attributes["connection"] = connection
        try:
            check(config)
            return True
        except AutogenerateDiffsDetected:
            return False


def test_stripping_on_update_makes_the_check_fail(engine, alembic_config):
    """compare_server_default's positive control."""
    assert _check_passes(engine, alembic_config), "the check was already failing before this test"

    restore = (
        "ALTER TABLE Segmentation MODIFY DateModified datetime NULL "
        "DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP"
    )
    try:
        with engine.begin() as conn:
            conn.execute(text(
                "ALTER TABLE Segmentation MODIFY DateModified datetime NULL "
                "DEFAULT CURRENT_TIMESTAMP"
            ))
        assert not _check_passes(engine, alembic_config), (
            "alembic check passed with ON UPDATE stripped from "
            "Segmentation.DateModified -- compare_server_default is not in force"
        )
    finally:
        with engine.begin() as conn:
            conn.execute(text(restore))

    assert _check_passes(engine, alembic_config), "restoring the clause did not clear the diff"


def test_changing_a_foreign_key_action_makes_the_check_fail(engine, alembic_config):
    """Row 4 of the drift table on PR #222, pinned.

    CASCADE -> RESTRICT, not RESTRICT -> NO ACTION: alembic normalises that
    pair deliberately and InnoDB treats them identically, so it would prove
    nothing. The constraint is unnamed in the migration, so MySQL named it.
    """
    assert _check_passes(engine, alembic_config), "the check was already failing before this test"

    with engine.connect() as conn:
        name = conn.execute(text(
            "SELECT rc.CONSTRAINT_NAME FROM information_schema.REFERENTIAL_CONSTRAINTS rc "
            "JOIN information_schema.KEY_COLUMN_USAGE kcu "
            "  ON kcu.CONSTRAINT_SCHEMA = rc.CONSTRAINT_SCHEMA "
            " AND kcu.CONSTRAINT_NAME = rc.CONSTRAINT_NAME "
            "WHERE rc.CONSTRAINT_SCHEMA = DATABASE() "
            "  AND rc.TABLE_NAME = 'Segmentation' "
            "  AND kcu.COLUMN_NAME = 'ImageInstanceID' "
            "  AND rc.DELETE_RULE = 'CASCADE'"
        )).scalar()
    assert name, "Segmentation.ImageInstanceID has no ON DELETE CASCADE key to mutate"

    def readd(action: str) -> str:
        return (
            f"ALTER TABLE Segmentation ADD CONSTRAINT `{name}` "
            "FOREIGN KEY (ImageInstanceID) REFERENCES ImageInstance (ImageInstanceID) "
            f"ON DELETE {action}"
        )

    drop = f"ALTER TABLE Segmentation DROP FOREIGN KEY `{name}`"
    try:
        with engine.begin() as conn:
            conn.execute(text(drop))
            conn.execute(text(readd("RESTRICT")))
        assert not _check_passes(engine, alembic_config), (
            f"alembic check passed with {name} changed from CASCADE to RESTRICT -- "
            "FK action drift is no longer detected"
        )
    finally:
        with engine.begin() as conn:
            conn.execute(text(drop))
            conn.execute(text(readd("CASCADE")))

    assert _check_passes(engine, alembic_config), "restoring the action did not clear the diff"


def test_upgrade_reconciles_legacy_annotationdata_datemodified(engine, alembic_config):
    """upgrade head gives the legacy-trail DateModified its declared default."""
    try:
        with engine.begin() as conn:
            conn.execute(text(
                "ALTER TABLE AnnotationData MODIFY DateModified datetime NULL ON UPDATE CURRENT_TIMESTAMP"
            ))
        with engine.connect() as connection:
            alembic_config.attributes["connection"] = connection
            stamp(alembic_config, "2db0e63195db")
            upgrade(alembic_config, "head")

        assert _check_passes(engine, alembic_config), "upgrade head left DateModified drift behind"
    finally:
        with engine.begin() as conn:
            conn.execute(text(
                "ALTER TABLE AnnotationData MODIFY DateModified datetime NULL "
                "DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP"
            ))
        with engine.connect() as connection:
            alembic_config.attributes["connection"] = connection
            stamp(alembic_config, "head")


def test_deleting_a_task_does_not_depend_on_foreign_key_order(engine):
    """TaskRepository.delete works when SubTask's key to Task sorts after fk_TaskProject_Task."""
    with engine.connect() as conn:
        name = conn.execute(text(
            "SELECT CONSTRAINT_NAME FROM information_schema.KEY_COLUMN_USAGE "
            "WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'SubTask' "
            "  AND COLUMN_NAME = 'TaskID' AND REFERENCED_TABLE_NAME = 'Task'"
        )).scalar_one()

    def rename(old: str, new: str) -> str:
        return (
            f"ALTER TABLE SubTask DROP FOREIGN KEY `{old}`, "
            f"ADD CONSTRAINT `{new}` FOREIGN KEY (TaskID) "
            "REFERENCES Task (TaskID) ON DELETE CASCADE"
        )

    # Sorts after fk_TaskProject_Task, as SubTask's key does on a lowercase server.
    with engine.begin() as conn:
        conn.execute(text(rename(name, "zz_SubTask_Task")))
    try:
        # Closing rolls back, so no rows are left behind, and must happen before
        # the restore: an open transaction's metadata lock would hang that ALTER.
        with Session(engine) as session:
            key = f"g{uuid4().hex[:8]}"
            project = make_project(session, key)
            study = make_study(session, make_patient(session, project, key), date(2024, 1, 1))
            image = make_image(
                session,
                make_series(session, study),
                make_device(session, key),
                make_storage_backend(session, key),
                key,
            )
            task = Task.create_from_imagesets(session, key, key, [[image]])
            session.add(task)
            session.flush()
            task_id = task.TaskID
            # Reload as delete_task does, so TaskProjects is not loaded.
            session.expunge_all()

            tasks = TaskRepository(session, scope=admin_scope())
            tasks.delete(tasks.get_by_id(task_id))

            assert session.scalar(select(Task.TaskID).where(Task.TaskID == task_id)) is None
    finally:
        with engine.begin() as conn:
            conn.execute(text(rename("zz_SubTask_Task", name)))
