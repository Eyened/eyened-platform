<p class="intro">
	Create and fill structured grading forms attached to the patient, study, or current
	image.
</p>

<section>
	<h2>Creating forms</h2>
	<ul>
		<li>Select a form type from the dropdown and click Create new form.</li>
		<li>
			When a task is active, the form type may be pre-selected from the task
			definition config.
		</li>
		<li>A shortcut button may appear for frequently used forms.</li>
	</ul>
</section>

<section>
	<h2>Scope</h2>
	<p>Study-eye forms are filtered by study date and laterality.</p>
	<p>Image-level forms are shown for the current image.</p>
	<p>ETDRS and registration schemas are managed in their dedicated panels, not here.</p>
</section>
