<p class="intro">
    Measure distances and areas on the image. Active when this panel is
    expanded.
</p>

<section>
    <h2>Using the measure tool</h2>
    <ul>
        <li>
            Click and drag to draw a line; release to see length in micrometers
            when resolution is known.
        </li>
        <li>End points can be dragged to move the line.</li>
        <li>
            Right click on an end point to delete the line, or delete from the
            list in the panel.
        </li>
    </ul>
</section>

<section>
    <h2>Image resolution</h2>
    <p>
        If the image has stored resolution metadata, measurements use those
        values.
    </p>
    <p>
        Expand Image resolution to set resolution manually or derive it from an
        ETDRS annotation (which has assumed to have a radius of 3 mm).
    </p>
</section>

<section>
    <h2>Segmentation area</h2>
    <p>Total area of all segmentations are listed in the panel.</p>
</section>
